class PostgresConnection:
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=()):
        sql = sql.replace("?", "%s")
        sql = sql.replace("telegram_id INTEGER", "telegram_id BIGINT")
        sql = sql.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
        if "INSERT OR IGNORE INTO" in sql:
            sql = sql.replace("INSERT OR IGNORE INTO", "INSERT INTO") + " ON CONFLICT DO NOTHING"
        if sql.strip() == "BEGIN IMMEDIATE":
            sql = "BEGIN"
        return self.connection.execute(sql, params)

@contextmanager
def db():
    if DATABASE_URL:
        import psycopg
        # Always require TLS when connecting to the remote Supabase database.
        with psycopg.connect(DATABASE_URL, sslmode="require", connect_timeout=12) as connection:
            yield PostgresConnection(connection)
    else:
        conn = sqlite3.connect(DB_PATH, timeout=15)
        try:
            conn.execute("PRAGMA journal_mode=WAL")
            yield conn
            conn.commit()
        except BaseException:
            conn.rollback()
            raise
        finally:
            conn.close()

